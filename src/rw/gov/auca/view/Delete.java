    private void btnToSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToSearchActionPerformed
        String ISBN = txtIsbnToSearch.getText().trim();
        
        BookInfo booToSearch = new BookInfo(ISBN);
        BookInfoDao dao = new BookInfoDao();
        BookInfo book = dao.SearcBook(booToSearch);
        txtIsbn.setText(book.getIsbn());
        txtTitle.setText(book.getTitle());
        txtAuthor.setText(book.getAuthor());
        txtPrice.setText(String.valueOf(book.getPrice()));
        txtQuantity.setText(String.valueOf(book.getQuantity()));
        txtCategory.setText(book.getCategory());
        txtPubYear.setText(String.valueOf(book.getPublicationYear()));
        txtIsbn.setEditable(false);
        
       
    }//GEN-LAST:event_btnToSearchActionPerformed

    private void btnToDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToDeleteActionPerformed
        String ISBN = txtIsbnToSearch.getText().trim();
        
        BookInfo book = new BookInfo(ISBN);
        BookInfoDao dao = new BookInfoDao();
        int answer = JOptionPane.showConfirmDialog(this, "Are sure you need to Delete this??","Deletion Form",JOptionPane.YES_NO_OPTION,JOptionPane.WARNING_MESSAGE);
        if (answer==JOptionPane.YES_OPTION) {
            int rowsAffected =dao.DeleteBook(book);
            if (rowsAffected>0) {
                JOptionPane.showMessageDialog(this, "Delete successfull!!!");
                LandingPage form = new LandingPage();
        form.setVisible(true);
        this.dispose();
            }
            else{
                JOptionPane.showMessageDialog(this, "Deletion Failure");
            }
        }
    }//GEN-LAST:event_btnToDeleteActionPerformed

