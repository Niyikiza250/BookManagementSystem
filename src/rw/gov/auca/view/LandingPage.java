    public int loadTable(){
        try {
            BookInfoDao tabledao = new BookInfoDao();
            List<BookInfo> BookToTable=tabledao.getAllBookInfos();
            DefaultTableModel model = (DefaultTableModel)TableForBook.getModel();
            model.setRowCount(0);
            for (BookInfo bookInfo : BookToTable) {
                model.addRow(new Object[]{
                    bookInfo.getIsbn(),
                    bookInfo.getTitle(),
                    bookInfo.getAuthor(),
                    bookInfo.getPrice(),
                    bookInfo.getQuantity(),
                    bookInfo.getCategory(),
                    bookInfo.getPublicationYear()
                });
                
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,"The Issue is " +e.getMessage());
        }
        return 0;
    }

