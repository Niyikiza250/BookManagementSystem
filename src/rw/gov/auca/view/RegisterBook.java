    private void btnToRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToRegisterActionPerformed
        String Isbn = txtIsbn.getText().trim();
        String Title = txtTitle.getText().trim();
        String Author = txtAuthor.getText().trim();
        Double Price = Double.parseDouble(txtPrice.getText().trim());
        int Quantity = Integer.parseInt(txtQuantity.getText().trim());
        String Category = txtCategory.getText().trim();
        int PubYear = Integer.parseInt(txtPubYear.getText().trim());
        
        BookInfo booToRegister = new BookInfo(Isbn, Title, Author, Price, Quantity, Category, PubYear);
        BookInfoDao toTableDao = new BookInfoDao();
        int rowsAffected = toTableDao.RegisterBook(booToRegister);
        if (rowsAffected>0) {
            JOptionPane.showMessageDialog(this,"Registration Successfull!!!!!" );
            LandingPage form = new LandingPage();
            form.loadTable();
            form.setVisible(true);
            this.dispose();
        }
        else{
            JOptionPane.showMessageDialog(this," Registration Failure ");
        }
        
    }//GEN-LAST:event_btnToRegisterActionPerformed

